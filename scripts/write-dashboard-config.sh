#!/usr/bin/env bash
# Generates dashboard/config.js from .env + deployments/*.env
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; source .env
for f in deployments/*.env; do [[ -f "$f" ]] && source "$f"; done
set +a

# Block where the reactive contract was deployed, so the dashboard can load the full arb history.
START_BLOCK="${REACTIVE_START_BLOCK:-}"
if [[ -z "$START_BLOCK" && -n "${REACTIVE_DEPLOY_TX:-}" ]]; then
  START_BLOCK=$(cast receipt "$REACTIVE_DEPLOY_TX" blockNumber --rpc-url "$REACTIVE_RPC" 2>/dev/null | awk '{print $1}' || true)
fi
[[ "$START_BLOCK" =~ ^[0-9]+$ ]] || START_BLOCK=0

cat > dashboard/config.js <<EOF
// Auto-generated by scripts/write-dashboard-config.sh — safe to edit by hand.
window.PARALLAX_CONFIG = {
  reactive: {
    name: "Reactive Lasna",
    chainId: ${REACTIVE_CHAIN_ID:-5318007},
    rpc: "${REACTIVE_RPC}",
    address: "${REACTIVE_ADDR:-}",
    startBlock: ${START_BLOCK},
    explorer: "https://lasna.reactscan.net"
  },
  venues: [
    {
      key: "UNI", name: "Unichain Sepolia", short: "Unichain", chainId: ${UNICHAIN_CHAIN_ID},
      rpc: "${UNICHAIN_SEPOLIA_RPC}", explorer: "https://sepolia.uniscan.xyz",
      pool: "${UNI_POOL:-}", executor: "${UNI_EXECUTOR:-}",
      base: "${UNI_BASE_TOKEN:-}", quote: "${UNI_QUOTE_TOKEN:-}"
    },
    {
      key: "BASE", name: "Base Sepolia", short: "Base", chainId: ${BASE_CHAIN_ID},
      rpc: "${BASE_SEPOLIA_RPC}", explorer: "https://sepolia.basescan.org",
      pool: "${BASE_POOL:-}", executor: "${BASE_EXECUTOR:-}",
      base: "${BASE_BASE_TOKEN:-}", quote: "${BASE_QUOTE_TOKEN:-}"
    }
  ],
  pollMs: 2000
};
EOF
echo "✓ dashboard/config.js written (history from Lasna block ${START_BLOCK})"
